#!/usr/bin/env python3
"""Build results/qaoa_mission_study/RESULTS_TABLES.md from the study JSON files."""

from __future__ import annotations

import json
import math
from collections import defaultdict
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "results" / "qaoa_mission_study"

FINDINGS = """## Key findings

**Problem.** Rover leaves base, visits N science sites on the lunar heightmap, returns.
Leg energies are direction-dependent (uphill costs more). Choosing the visiting order is
NP-hard (asymmetric TSP). 4-12 sites, 3-4 terrain instances per size, 5-29 qubits.

1. **QAOA learns, and more layers help.** With the compact encoding, the probability of
   sampling the optimal tour is 20-50x higher than random at depth p = 3-5, for every size
   from 6 to 12 sites (tables 1, 2, 8). One layer (p = 1) gives between 0.3x (worse than
   random) and 6x.
2. **Including training, QAOA beats random sampling only from about 9 sites.** Training
   costs about 380,000 shots on a real device (380 circuit evaluations x 1,000 shots). At 10
   sites QAOA needs ~6x10^5 samples in total vs ~1x10^7 for random (table 3).
3. **QAOA does not beat classical algorithms.** Exact Held-Karp solves every instance
   (4-12 sites) in at most 11 ms. One run of nearest-neighbour + 2-opt finds the optimum on
   23 of 33 instances and is within 3.4 % on the rest, in at most 1.1 ms (table 3). With
   random restarts, 2-opt reaches the optimum in a few thousand tour evaluations (table 8).
4. **In a fair black-box race it loses, and the gap grows with size.** Counting one tour
   evaluation as one query (= one QAOA shot) and ignoring QAOA's training cost, QAOA needed
   fewer queries than both 2-opt and simulated annealing on 7 of 27 instances, all with
   at most 7 sites. The mechanism is real: QAOA samples whole tours from a distribution
   biased toward low energy, so local optima do not trap it, and it won at 5, 6 and 7
   sites exactly on the instances where 2-opt was most trapped. But these wins vanish
   under the standard quantum query count (each of the p layers calls the cost function
   once, so a shot at p = 5 is 5 calls): 0 of 27. With training counted: 0 of 27. From 7
   to 12 sites, QAOA's disadvantage against 2-opt grows from 3x to about 18,000x (tables 7, 8).
5. **Why: a constant edge against factorial growth.** QAOA's advantage over random stays at
   about 25x while the number of tours grows as N! (479 million at 12 sites). 2-opt
   exploits the structure of the problem and its cost grows slowly.
6. **The standard (one-hot) encoding mostly learns the constraints.** It raises P(valid
   tour) a lot (up to ~1,000x at 5 sites, 25 qubits), but the valid tours it samples are
   only ~1 % better than random valid tours (table 4).
7. **Real hardware makes this harder.** One-hot QAOA at 8 sites needs 64 qubits and 5,040
   two-qubit gates at p = 3: estimated fidelity 0.6 % even at 0.1 % gate error (table 5).
   In noisy simulation at 1 % gate error, deeper circuits become worse than shallow ones
   (4 sites: p = 3 drops from 108x to 15x over random; p = 1 keeps 36x) (table 6).

**Caveats.** Compact encoding = cost lookup over all N! tours: valid for simulation,
not a realistic hardware circuit. Statevector simulation enumerates every answer, so CPU/GPU
time measures the simulator, not QAOA; this study therefore reports samples, queries and
circuit sizes. Depths above 5 and other QAOA variants (warm start, other mixers, parameter
transfer) were not tested.

**Bottom line.** QAOA genuinely beats random guessing on the NP-hard lunar mission and
improves with depth, but it does not beat classical algorithms, and its disadvantage grows
quickly with problem size, from 4 to 12 sites. A quantum advantage, if one exists here,
would need fault-tolerant hardware and better algorithms; this study does not show one."""


def load(name):
    path = DIR / name
    return json.load(open(path)) if path.exists() else []


def f(x, d=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    if isinstance(x, float) and math.isinf(x):
        return "never"
    if abs(x) >= 1e5 or (0 < abs(x) < 1e-3):
        return f"{x:.2e}"
    return f"{x:,.{d}f}"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def group(rows, *keys):
    g = defaultdict(list)
    for r in rows:
        g[tuple(r[k] for k in keys)].append(r)
    return dict(sorted(g.items()))


def med(rs, k):
    return float(np.median([r[k] for r in rs]))


def main():
    compact, onehot = load("compact.json"), load("onehot.json")
    gates, noisy = load("hw_gates.json"), load("hw_noisy.json")
    md = ["# QAOA on the multi-site lunar mission - result tables", "",
          "Generated by `scripts/qaoa_mission_report.py` from `results/qaoa_mission_study/*.json`.",
          "Values are medians over terrain instances (seeds) unless noted. QAOA runs alone:",
          "no classical seed, no repair, no fallback. 'Random' = uniformly random answers.", "",
          FINDINGS, ""]

    # 1. compact, best depth per N
    md += ["## 1. Compact encoding (every bitstring is a valid tour), best depth per N", ""]
    rows = []
    for (n,), rs in group(compact, "n_sites").items():
        pmax = max(r["p"] for r in rs)
        best = [r for r in rs if r["p"] == pmax]
        rows.append([n, best[0]["qubits"], len(best), pmax, f(med(best, "p_opt"), 4),
                     f(med(best, "uniform_p_opt"), 4), f(med(best, "amplification"), 2) + "x",
                     f(med(best, "gap_closed"), 2), f(med(best, "mean_ratio_qaoa"), 3),
                     f(med(best, "mean_ratio_uniform"), 3)])
    md += [table(["N sites", "qubits", "instances", "p", "P(optimal) QAOA", "P(optimal) random",
                  "amplification", "gap closed", "avg tour / optimum QAOA",
                  "avg tour / optimum random"], rows), ""]

    # 2. compact, amplification vs depth
    md += ["## 2. Compact encoding: amplification of P(optimal) over random, by depth p", ""]
    ps = sorted({r["p"] for r in compact})
    rows = []
    for (n,), rs in group(compact, "n_sites").items():
        byp = {p: [r for r in rs if r["p"] == p] for p in ps}
        rows.append([n, rs[0]["qubits"]] +
                    [f(med(byp[p], "amplification"), 2) + "x" if byp[p] else "-" for p in ps])
    md += [table(["N sites", "qubits"] + [f"p={p}" for p in ps], rows), ""]

    # 3. cost to solve: QAOA vs random vs classical
    md += ["## 3. Cost to find the optimal tour (99 % confidence)", "",
           "QAOA total = training (evaluations x 1,000 shots each, as a real device needs) "
           "+ samples to hit the optimum. Random = uniform samples to hit the optimum.", ""]
    rows = []
    for (n,), rs in group(compact, "n_sites").items():
        pmax = max(r["p"] for r in rs)
        best = [r for r in rs if r["p"] == pmax]
        rows.append([n, f(med(best, "shots_to_solution"), 0), f(med(best, "uniform_shots_to_solution"), 0),
                     f(med(best, "train_evals"), 0), f(med(best, "hw_total_samples"), 0),
                     f(med(best, "held_karp_ms"), 2) + " ms", f(med(best, "nn2opt_ratio"), 3),
                     f(med(best, "nn2opt_ms"), 2) + " ms"])
    md += [table(["N sites", "QAOA samples (trained)", "random samples", "QAOA training evals",
                  "QAOA total samples incl. training", "exact Held-Karp time",
                  "NN+2-opt tour / optimum", "NN+2-opt time"], rows), ""]

    # 4. one-hot
    if onehot:
        md += ["## 4. One-hot encoding (standard QUBO, N^2 qubits; most bitstrings invalid)", ""]
        rows = []
        for (n, p), rs in group(onehot, "n_sites", "p").items():
            rows.append([n, rs[0]["qubits"], p, len(rs), f(med(rs, "p_feasible"), 4),
                         f(med(rs, "uniform_p_feasible"), 4), f(med(rs, "p_opt"), 5),
                         f(med(rs, "uniform_p_opt"), 5), f(med(rs, "amplification"), 1) + "x",
                         f(med(rs, "mean_ratio_feasible_qaoa"), 3),
                         f(med(rs, "mean_ratio_feasible_uniform"), 3),
                         f(med(rs, "shots_to_solution"), 0), f(med(rs, "uniform_shots_to_solution"), 0)])
        md += [table(["N sites", "qubits", "p", "instances", "P(valid) QAOA", "P(valid) random",
                      "P(optimal) QAOA", "P(optimal) random", "amplification",
                      "valid tour / optimum QAOA", "valid tour / optimum random",
                      "QAOA samples to solve", "random samples to solve"], rows), ""]

    # 5. hardware gate counts
    if gates:
        md += ["## 5. Real-hardware circuit size (one-hot QAOA, all-to-all connectivity assumed)", "",
               "Estimated success fidelity = (1 - e)^CX for two-qubit error e. Routing on real "
               "chips adds more gates, so these are optimistic.", ""]
        rows = [[g["n_sites"], g["qubits"], g["p"], f"{g['cx']:,}", f"{g['depth']:,}",
                 f(g["fidelity_cx_1e-3"], 3), f(g["fidelity_cx_5e-3"], 3)] for g in gates]
        md += [table(["N sites", "qubits", "p", "CX gates", "depth",
                      "fidelity @ e=0.1 %", "fidelity @ e=0.5 %"], rows), ""]

    # 6. noisy simulation
    if noisy:
        md += ["## 6. Noisy simulation of trained one-hot circuits (depolarizing + readout error)", ""]
        rows = [[x["n_sites"], x["qubits"], x["p"], x["cx"], f"{x['error_2q'] * 100:.1f} %",
                 f(x["p_feasible"], 4), f(x["uniform_p_feasible"], 4),
                 f(x["p_opt"], 5), f(x["uniform_p_opt"], 5),
                 f(x["p_opt"] / x["uniform_p_opt"], 1) + "x"] for x in noisy]
        md += [table(["N sites", "qubits", "p", "CX", "2-qubit error", "P(valid)", "P(valid) random",
                      "P(optimal)", "P(optimal) random", "amplification"], rows), ""]

    # 7. black-box query race
    race = load("query_race.json")
    if race:
        md += ["## 7. Black-box query race: QAOA vs classical solvers that also only see tour energies", "",
               "One query = energy of one complete tour (= one QAOA shot). Queries for a 99 % chance "
               "of having found the optimal tour. Classical: 99th percentile over 300 runs. "
               "'QAOA no training' is deliberately generous to QAOA (training cost ignored).", ""]
        rows = []
        for (n,), rs in group(race, "n_sites").items():
            no_tr_wins = sum(r["qaoa_queries_no_training"] < min(r["two_opt_q99"], r["annealing_q99"])
                             for r in rs)
            tr_wins = sum(r["qaoa_queries_with_training"] < min(r["two_opt_q99"], r["annealing_q99"])
                          for r in rs)
            oracle_wins = sum(r["qaoa_queries_no_training"] * r["p"] < min(r["two_opt_q99"], r["annealing_q99"])
                              for r in rs)
            rows.append([n, rs[0]["qubits"], f(med(rs, "qaoa_queries_no_training"), 0),
                         f(float(np.median([r["qaoa_queries_no_training"] * r["p"] for r in rs])), 0),
                         f(med(rs, "qaoa_queries_with_training"), 0), f(med(rs, "two_opt_q99"), 0),
                         f(med(rs, "annealing_q99"), 0), f(med(rs, "random_queries"), 0),
                         f"{no_tr_wins}/{len(rs)}", f"{oracle_wins}/{len(rs)}", f"{tr_wins}/{len(rs)}"])
        md += [table(["N sites", "qubits", "QAOA shots (no training)", "QAOA cost-oracle calls (shots x p)",
                      "QAOA (with training)", "2-opt restarts", "simulated annealing", "random",
                      "QAOA wins: per shot", "QAOA wins: per oracle call", "QAOA wins: with training"],
                      rows), "",
               "*Per shot* counts one measured tour as one query. *Per oracle call* is the standard "
               "quantum query measure: every QAOA layer applies the cost function once, so one shot "
               "at depth p uses p cost evaluations. QAOA's small-N wins (all on instances where 2-opt "
               "was trapped by local optima) exist only under per-shot counting.", ""]

    # 8. full scaling N = 4..12 (CPU N<=10, GPU N=11,12), deepest p per instance
    gpu = load("gpu_scaleup.json")
    if race or gpu:
        md += ["## 8. Scaling to bigger missions (N = 11, 12 simulated on the RTX A5000 GPU)", "",
               "Deepest trained p per instance; queries for 99 % chance of the optimal tour. "
               "QAOA training cost NOT included (generous to QAOA).", ""]
        merged = []
        for r in race:
            merged.append({"n_sites": r["n_sites"], "qubits": r["qubits"],
                           "qaoa": r["qaoa_queries_no_training"], "two_opt": r["two_opt_q99"],
                           "sa": r["annealing_q99"], "random": r["random_queries"]})
        deepest = {}
        for r in gpu:
            k = (r["n_sites"], r["seed"])
            if k not in deepest or r["p"] > deepest[k]["p"]:
                deepest[k] = r
        for r in deepest.values():
            merged.append({"n_sites": r["n_sites"], "qubits": r["qubits"], "qaoa": r["shots_to_solution"],
                           "two_opt": r["two_opt_q99"], "sa": r["annealing_q99"],
                           "random": r["uniform_shots_to_solution"]})
        rows = []
        for (n,), rs in group(merged, "n_sites").items():
            q, t2 = med(rs, "qaoa"), med(rs, "two_opt")
            rows.append([n, rs[0]["qubits"], f"{math.factorial(n):,}", len(rs), f(q, 0), f(t2, 0),
                         f(med(rs, "sa"), 0), f(med(rs, "random"), 0), f(q / t2, 1) + "x"])
        md += [table(["N sites", "qubits", "possible tours", "instances", "QAOA queries",
                      "2-opt queries", "annealing queries", "random queries",
                      "QAOA / 2-opt (higher = QAOA worse)"], rows), ""]

    # raw per-instance
    md += ["## Appendix: every compact run", ""]
    rows = [[r["n_sites"], r["seed"], r["qubits"], r["p"], r["train_evals"], f(r["p_opt"], 4),
             f(r["uniform_p_opt"], 4), f(r["amplification"], 2), f(r["gap_closed"], 3),
             f(r["nn2opt_ratio"], 3)]
            for r in sorted(compact, key=lambda r: (r["n_sites"], r["seed"], r["p"]))]
    md += [table(["N", "seed", "qubits", "p", "evals", "P(opt) QAOA", "P(opt) random",
                  "amplification", "gap closed", "NN+2opt ratio"], rows), ""]

    out = DIR / "RESULTS_TABLES.md"
    out.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
